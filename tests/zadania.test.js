// Zadania na karcie leada i szansy, lista „Na dziś”, pobieranie danych firmy po NIP
const { boot, kit, ok, done } = require('./helpers');
const w = boot();
const { d, errs, click, submit, txt, E } = kit(w);
click('[data-act="demo-quick"]');
const id = E('db.deal.find(isOpen).id');
E(`openRecord('deal', '${id}')`);
ok(!!d.querySelector('#rec-tasks'), 'panel Zadania na karcie szansy');
click('[data-act="task-new"]');
submit('#taskForm');
ok(E('db.task.length') === 0, 'puste zadanie nie zapisuje się');
d.querySelector('#tk-title').value = 'Przygotować umowę';
d.querySelector('#tk-due').value = E('today');
submit('#taskForm');
ok(E('db.task.length') === 1 && E('db.task[0].rid') === id && E('db.task[0].title') === 'Przygotować umowę', 'zadanie zapisane przy szansie');
ok(/Przygotować umowę/.test(txt('#rec-tasks')), 'zadanie widać na karcie');
ok(E(`db.activity.some(a => a.rid === '${id}' && /Dodano zadanie/.test(a.text))`), 'dodanie zadania w historii');
click('[data-act="task-new"]');
d.querySelector('#tk-title').value = 'Zadanie na później';
d.querySelector('#tk-due').value = E('addDays(5)');
submit('#taskForm');
click('[data-act="go"][data-page="overview"]');
ok(/Przygotować umowę/.test(txt('.dash-grid')) && !/Zadanie na później/.test(txt('.dash-grid')), 'Na dziś pokazuje zadania z dzisiejszym terminem');
const tid = E('db.task[0].id');
click(`[data-act="done"][data-kind="task"][data-task="${tid}"]`);
ok(!!E('db.task[0].done'), 'zrobione z listy Na dziś');
ok(!/Przygotować umowę/.test(txt('.dash-grid')), 'zrobione znika z listy');
click('[data-act="toast-act"]');
ok(!E('db.task[0].done'), 'cofnięcie przywraca zadanie');
E(`openRecord('deal', '${id}')`);
click(`[data-act="task-del"][data-id="${tid}"]`);
ok(E('db.task.length') === 1, 'usunięcie zadania');
ok(JSON.parse(w.localStorage.getItem('hermes-crm-v3')).db.task.length === 1, 'zadania zapisują się w przeglądarce');
/* NIP: walidacja sumy kontrolnej i komunikat bez dostępu do rejestru */
click('[data-act="go"][data-page="list"][data-obj="company"]');
E("openAdd('company')");
ok(!!d.querySelector('#n-nip') && !!d.querySelector('[data-act="nip-fetch"]'), 'pole NIP z pobieraniem danych w formularzu firmy');
d.querySelector('#n-nip').value = '1234567890';
click('[data-act="nip-fetch"]');
ok(d.querySelector('#n-nip').classList.contains('err'), 'błędny NIP oznaczony');
ok(E('nipOk("5260250995")') && !E('nipOk("5260250996")'), 'suma kontrolna NIP');
done(errs);
